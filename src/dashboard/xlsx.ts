// A minimal Excel workbook (.xlsx, Office Open XML): one sheet, a bold frozen header
// with filters, set column widths, real dates. A .xlsx is a zip of XML files; this
// writes the zip uncompressed ("stored"), which every spreadsheet app opens.

export interface XlsxColumn {
  header: string;
  /** Width in characters. */
  width: number;
  /** "date" cells take epoch ms and show as yyyy-mm-dd hh:mm. */
  type?: "text" | "number" | "date";
}

const enc = new TextEncoder();

/** XML text: escaped, and characters XML can't carry dropped. */
function xmlText(v: string): string {
  return v
    // eslint-disable-next-line no-control-regex -- tab, newline and return are the control characters XML allows
    .replace(/[^\x09\x0A\x0D\x20-퟿-�\u{10000}-\u{10FFFF}]/gu, "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function colName(i: number): string {
  let s = "";
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

/** Excel's serial date (days since 1899-12-30) for a local time. */
function excelDate(ms: number): number {
  const d = new Date(ms);
  return (Date.UTC(d.getFullYear(), d.getMonth(), d.getDate(), d.getHours(), d.getMinutes(), d.getSeconds()) - Date.UTC(1899, 11, 30)) / 86_400_000;
}

function sheetXml(cols: readonly XlsxColumn[], rows: ReadonlyArray<ReadonlyArray<string | number>>): string {
  const last = colName(cols.length - 1);
  const cell = (c: number, r: number, v: string | number, header: boolean) => {
    const ref = `${colName(c)}${r}`;
    if (header) return `<c r="${ref}" s="1" t="inlineStr"><is><t>${xmlText(String(v))}</t></is></c>`;
    const type = cols[c].type ?? "text";
    if (type === "date" && typeof v === "number") return `<c r="${ref}" s="2"><v>${excelDate(v)}</v></c>`;
    if (type === "number" && typeof v === "number") return `<c r="${ref}"><v>${v}</v></c>`;
    return `<c r="${ref}" t="inlineStr"><is><t xml:space="preserve">${xmlText(String(v))}</t></is></c>`;
  };
  const body = [cols.map((c) => c.header), ...rows]
    .map((row, r) => `<row r="${r + 1}">${row.map((v, c) => cell(c, r + 1, v, r === 0)).join("")}</row>`)
    .join("");
  return (
    `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>` +
    `<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">` +
    `<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>` +
    `<cols>${cols.map((c, i) => `<col min="${i + 1}" max="${i + 1}" width="${c.width}" customWidth="1"/>`).join("")}</cols>` +
    `<sheetData>${body}</sheetData>` +
    `<autoFilter ref="A1:${last}${rows.length + 1}"/>` +
    `</worksheet>`
  );
}

